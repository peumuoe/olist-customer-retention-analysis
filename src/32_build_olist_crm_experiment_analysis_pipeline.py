"""Pre-build and validate an ITT CRM experiment analysis pipeline.

All event rows generated by this script are synthetic and must never be
interpreted as observed campaign outcomes.
"""

from pathlib import Path
from math import exp, log, sqrt
import hashlib

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact, norm


ROOT = Path(__file__).resolve().parents[1]
PLAN_PATH = ROOT / "data" / "processed" / "olist_crm_customer_execution_plan_dry_run.csv"
TABLES = ROOT / "outputs" / "tables"
PROCESSED = ROOT / "data" / "processed"

SYNTHETIC_PATH = PROCESSED / "olist_crm_synthetic_experiment_events.csv"
RESULT_PATH = TABLES / "olist_crm_synthetic_itt_analysis_results.csv"
SCENARIO_PATH = TABLES / "olist_crm_synthetic_scenario_summary.csv"
SPEC_PATH = TABLES / "olist_crm_experiment_analysis_spec.csv"
QUALITY_PATH = TABLES / "olist_crm_experiment_analysis_quality_checks.csv"
SUMMARY_PATH = TABLES / "olist_crm_experiment_analysis_build_summary.csv"

ALPHA = 0.05
BASELINE = 16 / 905
SCENARIOS = {
    "synthetic_null_effect": (BASELINE, BASELINE),
    "synthetic_relative_uplift_30pct": (BASELINE, BASELINE * 1.30),
    "synthetic_relative_uplift_75pct": (BASELINE, BASELINE * 1.75),
}


def deterministic_rank(frame, scenario, arm, event_name):
    return frame["customer_unique_id"].map(
        lambda value: hashlib.sha256(
            f"{scenario}|{arm}|{event_name}|{value}".encode("utf-8")
        ).hexdigest()
    )


def assign_exact_binary_events(frame, scenario, rate, event_name):
    result = pd.Series(False, index=frame.index)
    for arm, group in frame.groupby("experiment_arm"):
        count = int(round(len(group) * rate[arm]))
        order = deterministic_rank(group, scenario, arm, event_name).sort_values()
        result.loc[order.index[:count]] = True
    return result


def build_synthetic_events(plan):
    frames = []
    for scenario, (control_rate, treatment_rate) in SCENARIOS.items():
        frame = plan[[
            "customer_unique_id", "experiment_arm", "order_value_band",
            "state_bucket", "score_quintile", "repurchase_score",
            "randomization_stratum",
        ]].copy()
        frame["scenario"] = scenario
        frame["synthetic_data_flag"] = True
        frame["outcome_matured_flag"] = True
        frame["repeat_order_delivered_flag"] = assign_exact_binary_events(
            frame,
            scenario,
            {"control": control_rate, "treatment": treatment_rate},
            "repeat_order",
        )
        frame["message_delivery_flag"] = False
        treatment = frame["experiment_arm"].eq("treatment")
        delivered_treatment = assign_exact_binary_events(
            frame.loc[treatment],
            scenario,
            {"treatment": 0.90},
            "message_delivery",
        )
        frame.loc[delivered_treatment.index, "message_delivery_flag"] = (
            delivered_treatment
        )
        frame["unsubscribe_flag"] = assign_exact_binary_events(
            frame,
            scenario,
            {"control": 0.002, "treatment": 0.005},
            "unsubscribe",
        )
        frame["complaint_flag"] = assign_exact_binary_events(
            frame,
            scenario,
            {"control": 0.0005, "treatment": 0.0010},
            "complaint",
        )
        frame["contact_cost"] = np.where(treatment, 0.02, 0.0)
        frame["incentive_cost"] = 0.0
        frame["observed_repeat_contribution"] = np.where(
            frame["repeat_order_delivered_flag"], 20.0, 0.0
        )
        frame["analysis_warning"] = "SYNTHETIC_ONLY_NOT_OBSERVED_CAMPAIGN_DATA"
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def wilson_interval(successes, n, alpha=ALPHA):
    if n == 0:
        return np.nan, np.nan
    z = norm.ppf(1 - alpha / 2)
    p = successes / n
    denominator = 1 + z ** 2 / n
    center = (p + z ** 2 / (2 * n)) / denominator
    half = z / denominator * sqrt(
        p * (1 - p) / n + z ** 2 / (4 * n ** 2)
    )
    return center - half, center + half


def newcombe_difference_interval(x_t, n_t, x_c, n_c):
    p_t, p_c = x_t / n_t, x_c / n_c
    low_t, high_t = wilson_interval(x_t, n_t)
    low_c, high_c = wilson_interval(x_c, n_c)
    difference = p_t - p_c
    lower = difference - sqrt((p_t - low_t) ** 2 + (high_c - p_c) ** 2)
    upper = difference + sqrt((high_t - p_t) ** 2 + (p_c - low_c) ** 2)
    return lower, upper


def risk_ratio_interval(x_t, n_t, x_c, n_c):
    if x_t == 0 or x_c == 0:
        return np.nan, np.nan, np.nan
    ratio = (x_t / n_t) / (x_c / n_c)
    standard_error = sqrt(1 / x_t - 1 / n_t + 1 / x_c - 1 / n_c)
    z = norm.ppf(1 - ALPHA / 2)
    return ratio, exp(log(ratio) - z * standard_error), exp(
        log(ratio) + z * standard_error
    )


def binary_itt_result(frame, metric, role):
    mature = frame.loc[frame["outcome_matured_flag"]].copy()
    grouped = mature.groupby("experiment_arm")[metric].agg(["sum", "size"])
    x_t, n_t = int(grouped.loc["treatment", "sum"]), int(grouped.loc["treatment", "size"])
    x_c, n_c = int(grouped.loc["control", "sum"]), int(grouped.loc["control", "size"])
    p_t, p_c = x_t / n_t, x_c / n_c
    diff = p_t - p_c
    diff_low, diff_high = newcombe_difference_interval(x_t, n_t, x_c, n_c)
    rr, rr_low, rr_high = risk_ratio_interval(x_t, n_t, x_c, n_c)
    _, p_value = fisher_exact([[x_t, n_t - x_t], [x_c, n_c - x_c]])
    return {
        "metric": metric,
        "metric_role": role,
        "treatment_n": n_t,
        "control_n": n_c,
        "treatment_events": x_t,
        "control_events": x_c,
        "treatment_rate": p_t,
        "control_rate": p_c,
        "absolute_effect": diff,
        "absolute_effect_ci95_lower": diff_low,
        "absolute_effect_ci95_upper": diff_high,
        "risk_ratio": rr,
        "risk_ratio_ci95_lower": rr_low,
        "risk_ratio_ci95_upper": rr_high,
        "fisher_exact_p_value": p_value,
        "analysis_population": "intention_to_treat_outcome_matured",
    }


def continuous_itt_result(frame, metric, role):
    mature = frame.loc[frame["outcome_matured_flag"]]
    treatment = mature.loc[mature["experiment_arm"].eq("treatment"), metric]
    control = mature.loc[mature["experiment_arm"].eq("control"), metric]
    difference = treatment.mean() - control.mean()
    standard_error = sqrt(
        treatment.var(ddof=1) / len(treatment)
        + control.var(ddof=1) / len(control)
    )
    z = norm.ppf(1 - ALPHA / 2)
    return {
        "metric": metric,
        "metric_role": role,
        "treatment_n": len(treatment),
        "control_n": len(control),
        "treatment_events": np.nan,
        "control_events": np.nan,
        "treatment_rate": treatment.mean(),
        "control_rate": control.mean(),
        "absolute_effect": difference,
        "absolute_effect_ci95_lower": difference - z * standard_error,
        "absolute_effect_ci95_upper": difference + z * standard_error,
        "risk_ratio": np.nan,
        "risk_ratio_ci95_lower": np.nan,
        "risk_ratio_ci95_upper": np.nan,
        "fisher_exact_p_value": np.nan,
        "analysis_population": "intention_to_treat_outcome_matured",
    }


def analyze(events):
    rows = []
    for scenario, frame in events.groupby("scenario", sort=True):
        for metric, role in [
            ("repeat_order_delivered_flag", "primary"),
            ("unsubscribe_flag", "guardrail"),
            ("complaint_flag", "guardrail"),
        ]:
            row = binary_itt_result(frame, metric, role)
            row["scenario"] = scenario
            row["synthetic_data_flag"] = True
            rows.append(row)
        frame = frame.assign(
            net_observed_contribution=(
                frame["observed_repeat_contribution"]
                - frame["contact_cost"]
                - frame["incentive_cost"]
            )
        )
        row = continuous_itt_result(
            frame, "net_observed_contribution", "guardrail"
        )
        row["scenario"] = scenario
        row["synthetic_data_flag"] = True
        rows.append(row)
    return pd.DataFrame(rows)


def build_scenario_summary(results):
    primary = results.loc[results["metric"].eq("repeat_order_delivered_flag")].copy()
    primary["ci_excludes_zero"] = (
        primary["absolute_effect_ci95_lower"].gt(0)
        | primary["absolute_effect_ci95_upper"].lt(0)
    )
    primary["interpretation"] = np.where(
        primary["ci_excludes_zero"],
        "synthetic example detects a difference",
        "synthetic example is inconclusive; not evidence of no effect",
    )
    return primary[[
        "scenario", "treatment_n", "control_n", "treatment_events",
        "control_events", "treatment_rate", "control_rate",
        "absolute_effect", "absolute_effect_ci95_lower",
        "absolute_effect_ci95_upper", "risk_ratio",
        "fisher_exact_p_value", "ci_excludes_zero", "interpretation",
        "synthetic_data_flag",
    ]]


def build_analysis_spec():
    return pd.DataFrame([
        ("data_status", "real campaign results required; current outputs are synthetic validation only"),
        ("primary_estimand", "ITT risk difference in delivered repeat-order customer rate"),
        ("population", "all randomized customers with 30 complete outcome days"),
        ("treatment_handling", "retain failed delivery and unopened messages in assigned treatment arm"),
        ("primary_interval", "Newcombe-Wilson 95% confidence interval for independent proportions"),
        ("relative_measure", "risk ratio with log-scale 95% confidence interval"),
        ("primary_test", "two-sided Fisher exact test at alpha 0.05"),
        ("continuous_interval", "unadjusted mean difference normal 95% interval; bootstrap planned for real skewed values"),
        ("missing_outcome_rule", "not-yet-mature customers excluded until day 30; unexplained missingness reported, not silently dropped"),
        ("subgroup_rule", "Q3/Q4 and score-quintile effects are exploratory with interaction intervals"),
        ("peeking_rule", "no repeated early success declaration without pre-specified sequential correction"),
        ("decision_rule", "report effect size, interval, event counts, guardrails and cost; p-value alone is insufficient"),
    ], columns=["analysis_item", "pre_registered_rule"])


def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    PROCESSED.mkdir(parents=True, exist_ok=True)
    plan = pd.read_csv(PLAN_PATH, low_memory=False)
    events = build_synthetic_events(plan)
    results = analyze(events)
    scenarios = build_scenario_summary(results)
    spec = build_analysis_spec()

    primary = scenarios.set_index("scenario")
    maturity_probe = events.loc[
        events["scenario"].eq("synthetic_null_effect")
    ].copy()
    maturity_probe.loc[maturity_probe.index[:100], "outcome_matured_flag"] = False
    maturity_result = binary_itt_result(
        maturity_probe, "repeat_order_delivered_flag", "primary"
    )
    delivery_probe = events.loc[
        events["scenario"].eq("synthetic_null_effect")
    ].copy()
    delivery_probe["message_delivery_flag"] = False
    delivery_result = binary_itt_result(
        delivery_probe, "repeat_order_delivered_flag", "primary"
    )
    quality = pd.DataFrame([
        ("synthetic_flag_all_true", int(events["synthetic_data_flag"].sum()), len(events), events["synthetic_data_flag"].all()),
        ("scenario_count", events["scenario"].nunique(), 3, events["scenario"].nunique() == 3),
        ("rows_per_scenario", int(events.groupby("scenario").size().min()), len(plan), events.groupby("scenario").size().eq(len(plan)).all()),
        ("customer_uniqueness_within_scenario", int(events.groupby("scenario")["customer_unique_id"].nunique().min()), len(plan), events.groupby("scenario")["customer_unique_id"].nunique().eq(len(plan)).all()),
        ("all_outcomes_matured", int(events["outcome_matured_flag"].sum()), len(events), events["outcome_matured_flag"].all()),
        ("null_exact_event_difference", abs(int(primary.loc["synthetic_null_effect", "treatment_events"] - primary.loc["synthetic_null_effect", "control_events"])), 0, primary.loc["synthetic_null_effect", "treatment_events"] == primary.loc["synthetic_null_effect", "control_events"]),
        ("moderate_ci_includes_zero", bool(not primary.loc["synthetic_relative_uplift_30pct", "ci_excludes_zero"]), True, not primary.loc["synthetic_relative_uplift_30pct", "ci_excludes_zero"]),
        ("large_ci_excludes_zero", bool(primary.loc["synthetic_relative_uplift_75pct", "ci_excludes_zero"]), True, primary.loc["synthetic_relative_uplift_75pct", "ci_excludes_zero"]),
        ("primary_result_count", int(results["metric_role"].eq("primary").sum()), 3, results["metric_role"].eq("primary").sum() == 3),
        ("result_synthetic_flag_all_true", int(results["synthetic_data_flag"].sum()), len(results), results["synthetic_data_flag"].all()),
        ("maturity_probe_denominator", int(maturity_result["treatment_n"] + maturity_result["control_n"]), len(plan) - 100, maturity_result["treatment_n"] + maturity_result["control_n"] == len(plan) - 100),
        ("delivery_failure_kept_in_itt", int(delivery_result["treatment_n"] + delivery_result["control_n"]), len(plan), delivery_result["treatment_n"] + delivery_result["control_n"] == len(plan)),
    ], columns=["check_name", "actual_value", "expected_value", "passed"])
    if not quality["passed"].all():
        raise AssertionError(quality.loc[~quality["passed"]].to_dict("records"))

    events.to_csv(SYNTHETIC_PATH, index=False)
    results.to_csv(RESULT_PATH, index=False)
    scenarios.to_csv(SCENARIO_PATH, index=False)
    spec.to_csv(SPEC_PATH, index=False)
    quality.to_csv(QUALITY_PATH, index=False)
    quality.to_csv(SUMMARY_PATH, index=False)

    print("\nPRIMARY SYNTHETIC SCENARIOS\n", scenarios.to_string(index=False))
    print("\nQUALITY CHECKS\n", quality.to_string(index=False))


if __name__ == "__main__":
    main()
